export const PANELS = [
  'General',
  'Sprites',
  'Model',
  'Persona',
  'Voice',
  'Voice Input',
  'Appearance',
  'Advanced',
] as const;
export type Panel = (typeof PANELS)[number];
export type Setting = {
  id: number;
  panel: Panel;
  group: string;
  section: ConfigSection;
  key: string;
  label: string;
  kind:
    | 'toggle'
    | 'select'
    | 'number'
    | 'range'
    | 'text'
    | 'textarea'
    | 'color'
    | 'tags'
    | 'model'
    | 'font';
  options?: readonly (readonly [string, string])[];
  min?: number;
  max?: number;
  step?: number;
  multiplier?: number;
  reverse?: boolean;
  suffix?: string;
  hint?: string;
  synonyms?: string;
  restart?: boolean;
  rows?: number;
  maxLength?: number;
  placeholder?: string;
  visible?: (cfg: Config) => boolean;
  disabled?: (cfg: Config) => boolean;
  disabledHint?: string;
  unavailableOptions?: readonly string[];
};
const field = <S extends ConfigSection>(
  section: S,
  key: keyof Config[S] & string,
  definition: Omit<Setting, 'section' | 'key'>,
): Setting => ({ ...definition, section, key });
const general = (
  key: keyof Config['window'],
  definition: Omit<Setting, 'section' | 'key' | 'panel'>,
) => field('window', key, { ...definition, panel: 'General' });
const model = (key: keyof Config['llm'], definition: Omit<Setting, 'section' | 'key' | 'panel'>) =>
  field('llm', key, { ...definition, panel: 'Model' });
const bubble = (
  key: keyof Config['bubble'],
  definition: Omit<Setting, 'section' | 'key' | 'panel'>,
) => field('bubble', key, { ...definition, panel: 'Appearance' });
const input = (
  key: keyof Config['input'],
  definition: Omit<Setting, 'section' | 'key' | 'panel'>,
) => field('input', key, { ...definition, panel: 'Appearance' });
const notMock = (cfg: Config) => cfg.llm.provider !== 'mock';
const speech = (cfg: Config) => cfg.tts.provider !== 'none';
const voice = (
  key:
    | keyof Config['tts']
    | `elevenlabs.${keyof Config['tts']['elevenlabs']}`
    | `custom.${keyof Config['tts']['custom']}`,
  definition: Omit<Setting, 'section' | 'key' | 'panel'>,
): Setting => ({ ...definition, section: 'tts', key, panel: 'Voice' });
const eleven = (cfg: Config) => cfg.tts.provider === 'elevenlabs';
