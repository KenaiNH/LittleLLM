export function matchesSearch(label: string, query: string) {
  const haystack = label.toLocaleLowerCase();
  return query
    .toLocaleLowerCase()
    .trim()
    .split(/\s+/)
    .every((word) => {
      if (haystack.includes(word)) return true;
      let at = 0;
      for (const char of haystack) if (char === word[at]) at++;
      return at === word.length;
    });
}
